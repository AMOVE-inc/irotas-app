import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const inputPath = process.argv[2];
if (!inputPath) throw new Error("Usage: node scripts/build-gourmet-contest-import.mjs <discord-export.json>");

const root = process.cwd();
const publicDir = path.join(root, "public", "discord-gourmet-contests");
const outputPath = path.join(root, "constants", "imported-gourmet-contests.ts");
const source = JSON.parse(await readFile(inputPath, "utf8"));
await mkdir(publicDir, { recursive: true });

const extensionFor = (url) => {
  const pathname = new URL(url).pathname;
  const extension = path.extname(pathname).toLowerCase().replace(/[^.a-z0-9]/g, "");
  return extension || ".jpg";
};
const isVideo = (file) => /\.(mov|mp4|m4v|webm)$/i.test(file);

const attachmentJobs = [];
for (const contest of source) {
  for (const message of contest.messages) {
    if (Array.isArray(message.localAttachments)) continue;
    message.localAttachments = message.attachments.map((url, index) => {
      const file = `${String(contest.round).padStart(2, "0")}-${message.id}-${index + 1}${extensionFor(url)}`;
      attachmentJobs.push({ url, file });
      return `/discord-gourmet-contests/${file}`;
    });
  }
}

let cursor = 0;
let downloaded = 0;
const failures = [];
async function worker() {
  while (cursor < attachmentJobs.length) {
    const job = attachmentJobs[cursor++];
    try {
      const response = await fetch(job.url);
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      await writeFile(path.join(publicDir, job.file), Buffer.from(await response.arrayBuffer()));
      downloaded += 1;
      if (downloaded % 25 === 0) process.stdout.write(`Downloaded ${downloaded}/${attachmentJobs.length}\n`);
    } catch (error) {
      failures.push({ ...job, error: String(error) });
    }
  }
}
if (process.env.SKIP_DOWNLOAD !== "1") await Promise.all(Array.from({ length: 16 }, worker));
if (failures.length) {
  console.error(JSON.stringify(failures, null, 2));
  throw new Error(`${failures.length} attachment downloads failed`);
}

