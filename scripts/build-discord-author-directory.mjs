import fs from "node:fs";

const archives = ["../data/discord-board-2026-08-14.json", "../data/discord-board-2026-08-29.json"]
  .map((path) => JSON.parse(fs.readFileSync(new URL(path, import.meta.url), "utf8")));
const authors = new Map();

function remember(record) {
  const rawId = String(record.authorId ?? "").replace(/^discord-/, "");
  if (!rawId) return;
  const current = authors.get(rawId) ?? {};
  authors.set(rawId, {
    id: `discord-${rawId}`,
    name: record.authorName || current.name || "メンバー",
    avatarUrl: record.authorAvatarUrl || current.avatarUrl || "",
    rank: record.authorRank || current.rank || "regular",
  });
}

for (const archive of archives) {
  for (const thread of archive.threads ?? []) {
    remember(thread);
    for (const comment of thread.comments ?? []) remember(comment);
  }
}

const directory = [...authors.values()].sort((a, b) => a.id.localeCompare(b.id));
const output = `/* This file is generated by scripts/build-discord-author-directory.mjs. */\nexport type DiscordAuthorRecord = { id: string; name: string; avatarUrl: string; rank: string };\nexport const DISCORD_AUTHOR_DIRECTORY: DiscordAuthorRecord[] = ${JSON.stringify(directory, null, 2)};\n`;
fs.writeFileSync(new URL("../constants/discord-author-directory.ts", import.meta.url), output);
console.log(`generated ${directory.length} Discord authors`);
